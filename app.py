# المسارات والفرعيات
st.markdown("### 🔍 ثانياً: الاستنطاق المنهجي")
pillar = st.selectbox("1. حدد المسار الرئيسي:", list(methodology_dict.keys()))
report_type = st.selectbox("2. حدد نوع التقرير المنهجي:", list(methodology_dict[pillar].keys()))

st.success(f"المنهجية المطبقة: {report_type}")

# توليد الأسئلة المنهجية
final_answers = {}
q_list = methodology_dict[pillar][report_type]

for i, (q_t, q_h) in enumerate(q_list):
    final_answers[q_t] = st.text_area(f"{i+1}. {q_t}", placeholder=f"إرشاد: {q_h}", height=100)

st.markdown("---")

# الخواتيم
st.markdown("### 📝 ثالثاً: الاعتمادات")
recs = st.text_area("التوصيات والمقترحات الموجهة للإدارة العليا:")
files = st.text_input("الملاحق والشواهد المرفقة:")

# التوليد
if st.button("اعتماد وتوليد الوثيقة السيادية"):
    if not auth_code:
        st.error("⚠️ يرجى إدخال كود التفعيل.")
    elif not (org and proj and user_name):
        st.warning("⚠️ يرجى استكمال بيانات الغلاف.")
    else:
        try:
            genai.configure(api_key=st.secrets["GEMINI_API_KEY"])
            model = genai.GenerativeModel('gemini-1.5-pro')
            
            data_string = "\n".join([f"{k}: {v}" for k, v in final_answers.items() if v])
            prompt_final = f"""صغ تقرير '{report_type}' رسمي لجهة '{org}' حول مشروع '{proj}'. الموقع: {loc}. إعداد: {user_name}.
            المنهجية: {pillar}. البيانات: {data_string}. التوصيات: {recs}. الملاحق: {files}.
            ابدأ بالغلاف، ثم الملخص، ثم التحليل بلغة الأرقام، ثم الخواتيم."""
            
            with st.spinner("جاري الصياغة المنهجية..."):
                response = model.generate_content(prompt_final)
                st.info(response.text)
                
                doc = Document()
                doc.add_heading(f"{org} | {report_type}", 0).alignment = WD_ALIGN_PARAGRAPH.CENTER
                for line in response.text.split('\n'):
                    if line.strip():
                        p = doc.add_paragraph(line.strip())
                        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
                bio = io.BytesIO()
                doc.save(bio)
                st.download_button("تحميل الوثيقة المعتمدة (Word)", bio.getvalue(), file_name=f"{report_type}.docx")
        except Exception as e:
            st.error(f"خطأ: {e}")
