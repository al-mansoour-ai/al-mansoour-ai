    st.info(f"الجهاز مسجل بالمعرف: {st.session_state.device_id[-6:]}")
    
    st.write("المنصة للمشتركين المعتمدين فقط. سجل دخولك:")
    user_id = st.text_input("أدخل رقم الجوال أو البريد الإلكتروني:")
    
    if st.button("تسجيل الدخول", use_container_width=True):
        if user_id:
            st.session_state.logged_in = True
            st.session_state.user_id = user_id
            st.session_state.current_page = "platform"
            st.rerun()
        else:
            st.warning("يرجى إدخال رقم الجوال للمتابعة.")
    st.markdown('</div>', unsafe_allow_html=True)

